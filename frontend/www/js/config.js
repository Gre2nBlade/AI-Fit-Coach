// Адрес бэкенда. Меняется в ОДНОМ месте.
//
// ┌─ В браузере на ПК ───────────────────────────────────────────────┐
// │  http://localhost:8000   (значение по умолчанию ниже)            │
// └──────────────────────────────────────────────────────────────────┘
// ┌─ В APK на телефоне ──────────────────────────────────────────────┐
// │  Телефон НЕ видит localhost ПК. Нужен ЛОКАЛЬНЫЙ IP ПК в той же    │
// │  Wi-Fi сети — он выглядит как 192.168.x.x или 10.x.x.x,           │
// │  НЕ публичный (НЕ 2.x / 5.x / 95.x и т.п.).                       │
// │                                                                  │
// │  Как узнать и включить (Windows):                                │
// │   1) В терминале: ipconfig  → строка «IPv4-адрес» Wi-Fi-адаптера │
// │      например 192.168.0.15                                       │
// │   2) Впиши его сюда:  http://192.168.0.15:8000                   │
// │   3) Открой порт 8000 в брандмауэре (PowerShell от админа):      │
// │      netsh advfirewall firewall add rule name="AFC 8000" \       │
// │        dir=in action=allow protocol=TCP localport=8000           │
// │   4) Бэкенд должен слушать 0.0.0.0:8000 (уже так в .env).        │
// │   5) Проверь с телефона в браузере:                             │
// │      http://192.168.0.15:8000/health  → {"status":"ok"}          │
// │   ПК и телефон обязаны быть в ОДНОЙ Wi-Fi сети.                  │
// └──────────────────────────────────────────────────────────────────┘
window.AFC_API_BASE = "http://192.168.0.15:8000";
