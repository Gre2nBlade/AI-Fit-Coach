// Адрес бэкенда. Меняется в ОДНОМ месте — здесь.
//
// ┌─ В браузере на ПК (разработка) ──────────────────────────────────┐
// │  http://localhost:8000                                            │
// └──────────────────────────────────────────────────────────────────┘
// ┌─ В APK на телефоне — чтобы работало С ЛЮБОГО Wi-Fi и мобильного ──┐
// │  Телефон НЕ видит ни localhost ПК, ни его локальный IP вне твоей  │
// │  домашней сети. Поэтому бэкенд выставляется наружу через ТУННЕЛЬ, │
// │  который даёт ПУБЛИЧНЫЙ https-адрес. Его и вписываем сюда.        │
// │                                                                  │
// │  Используем Cloudflare Tunnel (cloudflared) — работает в РФ.     │
// │   1) Установи cloudflared (см. scripts/serve-public.sh или       │
// │      README → «Запуск с публичным доступом (туннель)»).          │
// │   2) Запусти бэкенд + туннель:  bash scripts/serve-public.sh    │
// │   3) Скопируй выданный https-адрес, напр.                        │
// │      https://random-words-1234.trycloudflare.com                 │
// │   4) Впиши его в строку window.AFC_API_BASE ниже (без / в конце).│
// │   5) Пересобери фронт в APK:  cd frontend && npx cap sync android│
// │   6) Проверь:  <твой-адрес>/health  →  {"status":"ok"}           │
// │                                                                  │
// │  Бэкенд уже слушает 0.0.0.0:8000 и CORS=* — отдельно настраивать │
// │  ничего не нужно. Бэкенд + туннель должны быть запущены, когда   │
// │  приложением пользуются.                                         │
// └──────────────────────────────────────────────────────────────────┘
//
// Для локальной разработки в браузере на ПК достаточно localhost:
//   window.AFC_API_BASE = "http://localhost:8000";
//
// ┌─ Свой сервер со СТАТИЧЕСКИМ (белым) IP ──────────────────────────┐
// │  Если у тебя есть сервер с постоянным внешним IP — туннель не     │
// │  нужен, впиши адрес напрямую:                                     │
// │     window.AFC_API_BASE = "http://203.0.113.10:8000";            │
// │  По возможности используй HTTPS + домен (например через           │
// │  Nginx/Caddy + Let's Encrypt):                                    │
// │     window.AFC_API_BASE = "https://api.твойдомен.ru";            │
// │  Чистый http уже разрешён в APK (capacitor.config.json →          │
// │  cleartext:true), но https надёжнее и не блокируется браузерами.  │
// │  Важно: «проблемы с питанием» сервера = простой по аптайму, IP    │
// │  тут ни при чём — нужен бесперебойник/VPS, а не туннель.          │
// └──────────────────────────────────────────────────────────────────┘

window.AFC_API_BASE = "http://2.27.63.201:8000";
